/** Emoji drapeau pour un combattant (champ `country` du roster). */
export function getCountryFlagEmoji(country?: string | null): string {
  if (!country?.trim()) return '🏳️'
  const key = normalizeCountryKey(country)
  return COUNTRY_FLAGS[key] ?? '🏳️'
}

/** Libellé lisible du pays (conserve la casse d’origine si connue). */
export function formatCountryLabel(country?: string | null): string | null {
  if (!country?.trim() || normalizeCountryKey(country) === 'unknown') return null
  return country.trim()
}
